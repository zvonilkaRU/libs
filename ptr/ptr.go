// Package ptr — хелперы для работы с указателями при сборке DTO.
//
// Типовой сценарий: маппинг между доменом и OpenAPI-моделями, где
// опциональные поля описаны указателями, а в домене лежат значения
// (zero-значение = «не задано»). Обратное направление — &value — с
// Go 1.26 закрывается нативным new(expr) и хелпером не является.
package ptr

// ValOrNil возвращает nil для zero-значения (пустая строка, 0, false
// и т.п.) и указатель на значение в остальных случаях: zero в домене
// маппится в nil-поле DTO, а не в указатель на пустую строку.
func ValOrNil[T comparable](v T) *T {
	var zero T
	if v == zero {
		return nil
	}

	return &v
}

// Val разыменовывает указатель, возвращая zero-значение для nil:
// nil-поле DTO маппится в zero домена без отдельной ветки if.
func Val[T any](p *T) T {
	if p == nil {
		var zero T

		return zero
	}

	return *p
}
